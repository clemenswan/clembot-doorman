#!/usr/bin/env node
/**
 * Publish the pattern cards to the authority.
 *
 * Emits SQL on stdout rather than talking to D1 itself. Two reasons, and the
 * second is the real one:
 *
 *   1. Zero dependencies, like everything else here.
 *   2. A seed that writes directly is a seed nobody reads before it runs.
 *      Printing the statements means the diff is reviewable, and publishing is
 *      an explicit act by a human holding credentials rather than a side
 *      effect of running a script.
 *
 *   node scripts/seed-patterns.mjs                     # review it
 *   node scripts/seed-patterns.mjs | npx wrangler d1 execute mcp-scorecard --remote --command-file=-
 *
 * The cards are the SAME files the plugin bundles, so the authority and the
 * offline snapshot cannot disagree about what a card says. One source, two
 * readers: a second copy authored for the server is how the bundled fallback
 * quietly becomes a different product.
 */

import { readdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const CARDS = join(HERE, '..', '..', 'authority', 'patterns');

/** SQL string literal. Doubling the quote is the whole escape rule in SQLite. */
const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

const EFFORTS = new Set(['S', 'M', 'L']);

export function cardToSql(c, now) {
  // Validate before emitting, not after. A malformed card that reaches the
  // table is a card the dashboard renders as authoritative.
  if (!/^[a-z0-9-]{1,64}$/.test(String(c.id ?? ''))) throw new Error(`bad id: ${c.id}`);
  if (!Number.isInteger(c.dimension) || c.dimension < 1 || c.dimension > 7) {
    throw new Error(`${c.id}: dimension must be 1-7, got ${c.dimension}`);
  }
  if (!EFFORTS.has(c.effort)) throw new Error(`${c.id}: effort must be S, M or L`);
  for (const f of ['title', 'why', 'fix']) {
    if (typeof c[f] !== 'string' || !c[f].trim()) throw new Error(`${c.id}: ${f} is required`);
  }
  if (!Array.isArray(c.graded_mcps)) throw new Error(`${c.id}: graded_mcps must be an array`);

  return 'INSERT INTO patterns (id, dimension, title, why, fix, effort, evidence_url, graded_mcps, updated_at)\n'
    + `VALUES (${q(c.id)}, ${c.dimension}, ${q(c.title)}, ${q(c.why)}, ${q(c.fix)}, `
    + `${q(c.effort)}, ${q(c.evidence_url ?? null)}, ${q(JSON.stringify(c.graded_mcps))}, ${q(now)})\n`
    + 'ON CONFLICT(id) DO UPDATE SET\n'
    + '  dimension=excluded.dimension, title=excluded.title, why=excluded.why,\n'
    + '  fix=excluded.fix, effort=excluded.effort, evidence_url=excluded.evidence_url,\n'
    + '  graded_mcps=excluded.graded_mcps, updated_at=excluded.updated_at;';
}

export function readCards(dir = CARDS) {
  return readdirSync(dir).filter((f) => f.endsWith('.json')).sort()
    .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')));
}

function main() {
  const now = new Date().toISOString();
  const cards = readCards();
  const seen = new Set();
  const out = [];
  out.push('-- Generated by scripts/seed-patterns.mjs. Do not hand-edit.');
  out.push(`-- ${cards.length} card(s) at ${now}`);
  out.push('');
  for (const c of cards) {
    if (seen.has(c.id)) throw new Error(`duplicate card id: ${c.id}`);
    seen.add(c.id);
    out.push(cardToSql(c, now));
    out.push('');
  }
  // Deliberately NOT a DELETE of everything else. A seed that clears the table
  // first turns a partial run into an empty authority, and the dashboard
  // cannot tell an empty authority from a clean build.
  out.push('-- Rows not listed above are left alone on purpose: a seed that cleared');
  out.push('-- the table first would turn a partial run into an empty authority.');
  console.log(out.join('\n'));
}

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, '/')}`
  || process.argv[1]?.endsWith('seed-patterns.mjs')) {
  try {
    main();
  } catch (e) {
    console.error(`seed-patterns: ${e.message}`);
    process.exitCode = 1;
  }
}
